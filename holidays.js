const ranges = [
  ['2026-01-01', '03', '元旦'], ['2026-02-15', '23', '春节'],
  ['2026-04-04', '06', '清明'], ['2026-05-01', '05', '劳动节'],
  ['2026-06-19', '21', '端午'], ['2026-09-25', '27', '中秋'],
  ['2026-10-01', '07', '国庆'], ['2027-01-01', '03', '元旦'],
  ['2027-02-05', '13', '春节'], ['2027-04-03', '05', '清明'],
  ['2027-05-01', '05', '劳动节'], ['2027-06-09', '09', '端午'],
  ['2027-09-15', '15', '中秋'], ['2027-10-01', '07', '国庆']
]
function holiday(date) {
  const match = ranges.find(([start, end]) => date >= start && date <= start.slice(0, 8) + end)
  return match ? match[2] : ''
}
export default holiday
